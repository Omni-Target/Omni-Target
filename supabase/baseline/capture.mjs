#!/usr/bin/env node
/**
 * Turns a schema-only pg_dump of `public` into the provisioning baseline
 * (Phase 1, task 2). Usage:
 *
 *   pg_dump --schema-only --schema=public --no-owner <connection> > raw.sql
 *   node supabase/baseline/capture.mjs raw.sql supabase/baseline/catalog-0017.json > supabase/baseline/0017_schema.sql
 *
 * Changes made to the dump, and nothing else:
 *   - psql-only `\restrict` / `\unrestrict` lines are removed, so it runs through any client;
 *   - `CREATE SCHEMA public` tolerates an existing schema;
 *   - grants to operational roles (the backup role) are removed: each environment creates its own;
 *   - the applied migration IDs from the catalog are recorded in schema_migrations.
 */
import { readFileSync } from "node:fs";

const [rawPath, catalogPath] = process.argv.slice(2);
if (!rawPath || !catalogPath) {
  console.error("Usage: capture.mjs <raw schema dump> <catalog json>");
  process.exit(2);
}

const OPERATIONAL_ROLES = /\bomnitarget_backup\b/;
const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));
const lines = readFileSync(rawPath, "utf8").split("\n");

const kept = lines
  .filter((line) => !/^\\(un)?restrict\b/.test(line))
  .filter((line) => !OPERATIONAL_ROLES.test(line))
  .map((line) => (line === "CREATE SCHEMA public;" ? "CREATE SCHEMA IF NOT EXISTS public;" : line));

const ids = catalog.migrations ?? [];
const header = [
  "-- Omnitarget schema baseline at migration " + (ids.at(-1) ?? "unknown") + ".",
  "-- Generated by supabase/baseline/capture.mjs from a schema-only dump of the staging",
  "-- database. It reflects the intended schema, not production; production is",
  "-- reconciled against the finished migration set at release. Do not edit by hand.",
  "",
];
const footer = [
  "",
  "-- Migrations represented by this baseline.",
  ...ids.map((id) => `INSERT INTO public.schema_migrations (id) VALUES ('${id.replace(/'/g, "''")}') ON CONFLICT DO NOTHING;`),
  "",
];

process.stdout.write([...header, ...kept, ...footer].join("\n"));
